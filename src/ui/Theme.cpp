void ui_fonts(impl::UiState &ui) {
    ImGuiIO &io = ImGui::GetIO();

    // ImGui 1.92 rasterizes glyphs on demand, so the size is a STYLE
    // number rather than a property of the atlas: one TTF serves every
    // size the UI asks for, which is what lets a theme change its text
    // size without rebuilding anything. The bytes are ours and must
    // not be freed.
    ImFontConfig cfg;
    cfg.FontDataOwnedByAtlas = false;
    cfg.OversampleH = 2;
    cfg.OversampleV = 1;
    io.Fonts->AddFontFromMemoryTTF(const_cast<unsigned char *>(sv_font_sans),
                                   int(sizeof sv_font_sans), 0.0f, &cfg);
    // A second face for NUMBERS. Digits that do not share a width make
    // a column of readouts jump as the last figure changes, which is
    // the one thing a reader is watching for.
    ui.mono = io.Fonts->AddFontFromMemoryTTF(
        const_cast<unsigned char *>(sv_font_mono), int(sizeof sv_font_mono),
        0.0f, &cfg);
}

void ui_style(const Theme &t) {
    const Roles p{t};
    ImGuiStyle &s = ImGui::GetStyle();
    s.FontSizeBase = t.font_size;
    colours(s, p);
    metrics(s, t);
    plot_theme(t, p);
}

