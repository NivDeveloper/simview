// One look for every widget, derived from EIGHT colours and four
// numbers.
//
// A Theme carries roles, not settings: ink, panel, sunken, field,
// edge, text, dim text, accent, and the eight series colours. Every
// one of the ~55 ImGui colours, ~20 ImPlot colours and ~12 ImPlot3D
// colours below is one of those, one of those faded, or one of those
// mixed toward another — so a hover state cannot drift out of step
// with the surface it brightens, and a light theme gets correct hover
// polarity for free (mixing toward `text` darkens when text is dark).
//
// What the default theme decides, and why: the scene is near-black
// with a cool grey grid, and the DATA owns warm — a turbo ramp's high
// end is red. So the chrome is a cool, desaturated slate with a
// single azure accent, because a panel that also shouts in red makes
// the reader work out which red is the measurement. A theme that
// keeps that separation is a theme worth having; one that does not is
// how a screenshot stops meaning anything.
//
// The typefaces are embedded from the pinned imgui checkout (Fonts.h is
// generated by CMake), so an installed binary carries its own text and
// reads nothing from disk.

