// Rounding, borders and the space between things. ImGui's defaults are
// tuned for a debug overlay: square, tight, and every control the same
// weight. A control panel a person reads for an hour wants air.
//
// Two numbers carry all of it. `density` scales every gap at once, so
// compact and airy are one knob rather than nine that can disagree;
// `rounding` sets the window and the rest follow it in fixed
// proportion, because a panel rounder than the field inside it is what
// makes a theme look assembled rather than designed.
void metrics(ImGuiStyle &s, const Theme &t) {
    const float d = t.density;
    const float r = t.rounding;

    s.WindowPadding = ImVec2(11.0f * d, 9.0f * d);
    s.FramePadding = ImVec2(8.0f * d, 4.0f * d);
    s.CellPadding = ImVec2(7.0f * d, 4.0f * d);
    s.ItemSpacing = ImVec2(9.0f * d, 7.0f * d);
    s.ItemInnerSpacing = ImVec2(7.0f * d, 5.0f * d);
    s.IndentSpacing = 18.0f * d;
    s.ScrollbarSize = 11.0f * d;
    s.GrabMinSize = 11.0f * d;

    s.WindowBorderSize = t.border;
    s.ChildBorderSize = t.border;
    s.PopupBorderSize = t.border;
    s.FrameBorderSize = 0.0f;
    s.TabBorderSize = 0.0f;
    s.TabBarBorderSize = t.border;
    s.SeparatorTextBorderSize = 1.0f;

    // Exact fractions, not decimals near them: the ratios ARE the
    // design, and a check that pins a rounding to 4 should not fail on
    // 4.02.
    s.WindowRounding = r;
    s.ChildRounding = r * 5.0f / 6.0f;
    s.FrameRounding = r * 2.0f / 3.0f;
    s.PopupRounding = r * 5.0f / 6.0f;
    s.ScrollbarRounding = r;
    s.GrabRounding = r * 5.0f / 6.0f;
    s.TabRounding = r * 2.0f / 3.0f;

    // A title left-aligned reads as a label on the panel; centred it
    // reads as a heading, which is a weight this content does not have.
    s.WindowTitleAlign = ImVec2(0.0f, 0.5f);
    s.SeparatorTextAlign = ImVec2(0.0f, 0.5f);
    s.SeparatorTextPadding = ImVec2(18.0f * d, 5.0f * d);
    s.ButtonTextAlign = ImVec2(0.5f, 0.5f);
    s.SelectableTextAlign = ImVec2(0.0f, 0.5f);

    // Greyed, not ghostly: a disabled control still has to be readable
    // enough to say what it would do.
    s.DisabledAlpha = 0.45f;
    s.WindowMenuButtonPosition = ImGuiDir_None;
    s.AntiAliasedLines = true;
    s.AntiAliasedLinesUseTex = true;
    s.AntiAliasedFill = true;
}

// The series palette is the theme's, and the one place a data colour
// is chosen. It OPENS on the UI accent, so the first series and the
// chrome are the same hue and a one-series plot needs no legend to be
// read; the rest hold a similar lightness against that theme's ground,
// so no series shouts louder than another.
//
// A CONTINUOUS field is a different question and gets a different
// answer — see plot_colormap.
//
// ImPlot has no way to REPLACE a colormap, so a theme cannot reuse the
// name: the eight colours are hashed and the hash is the name. Two
// themes sharing a palette then share one registration, and switching
// back to a theme already seen finds its own. ImPlot and ImPlot3D keep
// SEPARATE registries, so each is asked separately — an unregistered
// 3D plot silently falls back to its own defaults, which is how the
// two libraries drift apart while every value in this file looks right.
struct Series {
    ImVec4 c[8];
    char name[16];
};

Series series_of(const Theme &t) {
    Series out{};
    std::uint32_t h = 2166136261u;
    for (int i = 0; i < 8; ++i) {
        out.c[i] = rgb(t.series[i]);
        for (int k = 0; k < 3; ++k) {
            const auto q = std::uint32_t(t.series[i][k] * 255.0f + 0.5f);
            h = (h ^ q) * 16777619u;
        }
    }
    std::snprintf(out.name, sizeof out.name, "sv%08x", h);
    return out;
}

ImPlotColormap series_colormap(const Series &s) {
    const ImPlotColormap found = ImPlot::GetColormapIndex(s.name);
    return found != -1 ? found : ImPlot::AddColormap(s.name, s.c, 8);
}

ImPlot3DColormap series_colormap3(const Series &s) {
    const ImPlot3DColormap found = ImPlot3D::GetColormapIndex(s.name);
    return found != -1 ? found : ImPlot3D::AddColormap(s.name, s.c, 8);
}

void plot_theme(const Theme &t, const Roles &p) {
    const Series series = series_of(t);
    const float gap = t.density;
    ImPlotStyle &a = ImPlot::GetStyle();
    ImVec4 *c = a.Colors;
    c[ImPlotCol_FrameBg] = fade(p.ink, 0.0f);
    c[ImPlotCol_PlotBg] = fade(p.sunken, 0.65f);
    c[ImPlotCol_PlotBorder] = p.edge;
    // The legend sits ON the data by default, so it is translucent:
    // a reader should be able to see what it covers.
    c[ImPlotCol_LegendBg] = fade(p.ink, 0.72f);
    c[ImPlotCol_LegendBorder] = p.edge;
    c[ImPlotCol_LegendText] = p.text;
    c[ImPlotCol_TitleText] = p.text;
    c[ImPlotCol_InlayText] = p.dim;
    c[ImPlotCol_AxisText] = p.dim;
    c[ImPlotCol_AxisGrid] = fade(p.edge, 0.55f);
    c[ImPlotCol_AxisTick] = p.edge;
    c[ImPlotCol_AxisBg] = fade(p.ink, 0.0f);
    c[ImPlotCol_AxisBgHovered] = fade(p.accent, 0.20f);
    c[ImPlotCol_AxisBgActive] = fade(p.accent, 0.32f);
    c[ImPlotCol_Selection] = p.accent_hot;
    c[ImPlotCol_Crosshairs] = fade(p.text, 0.55f);

    // The axis furniture. ImPlot's ticks are 10px long and its labels
    // sit 5px off the frame, which reads as a ruler pressed against the
    // data; short ticks with room around the numbers read as a scale.
    // Tick DENSITY is not ours — ImPlot's locator targets a fixed
    // pixels-per-tick and exposes no knob for it.
    a.PlotPadding = ImVec2(12.0f * gap, 10.0f * gap);
    a.LabelPadding = ImVec2(7.0f * gap, 6.0f * gap);
    a.MajorTickLen = ImVec2(6.0f * gap, 6.0f * gap);
    a.MinorTickLen = ImVec2(3.0f * gap, 3.0f * gap);
    a.MajorTickSize = ImVec2(1.0f, 1.0f);
    a.MinorTickSize = ImVec2(1.0f, 1.0f);
    // A curve that touches the frame reads as clipped. A fitted axis
    // leaves a little room, more above and below than left and right,
    // because that is where a peak lands.
    a.FitPadding = ImVec2(0.02f, 0.07f);
    a.LegendPadding = ImVec2(9.0f * gap, 9.0f * gap);
    a.LegendInnerPadding = ImVec2(6.0f * gap, 4.0f * gap);
    a.PlotBorderSize = 0.0f;
    a.MinorAlpha = 0.18f;
    a.Colormap = series_colormap(series);

    ImPlot3DStyle &q = ImPlot3D::GetStyle();
    q.LineWeight = 1.75f;
    q.MarkerSize = 3.0f;
    q.FillAlpha = 0.60f;
    q.PlotPadding = ImVec2(11.0f * gap, 9.0f * gap);
    q.Colormap = series_colormap3(series);
    ImVec4 *d = q.Colors;
    d[ImPlot3DCol_FrameBg] = fade(p.ink, 0.0f);
    d[ImPlot3DCol_PlotBg] = fade(p.sunken, 0.65f);
    d[ImPlot3DCol_PlotBorder] = p.edge;
    d[ImPlot3DCol_LegendBg] = fade(p.ink, 0.72f);
    d[ImPlot3DCol_LegendBorder] = p.edge;
    d[ImPlot3DCol_LegendText] = p.text;
    d[ImPlot3DCol_TitleText] = p.text;
    d[ImPlot3DCol_InlayText] = p.dim;
    d[ImPlot3DCol_AxisText] = p.dim;
    d[ImPlot3DCol_AxisGrid] = fade(p.edge, 0.55f);
    d[ImPlot3DCol_AxisTick] = p.edge;
}

