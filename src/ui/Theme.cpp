    c[ImGuiCol_ResizeGrip] = fade(p.dim, 0.25f);
    c[ImGuiCol_ResizeGripHovered] = fade(p.accent, 0.55f);
    c[ImGuiCol_ResizeGripActive] = p.accent;

    c[ImGuiCol_Tab] = fade(p.sunken, 0.90f);
